"use client";

import * as React from "react";

import { DialogContent as BaseDialogContent } from "@/components/ui/dialog";

export {
  Dialog,
  DialogClose,
  DialogDescription,
  DialogFooter,
  DialogHeader,
  DialogOverlay,
  DialogPortal,
  DialogTitle,
  DialogTrigger,
} from "@/components/ui/dialog";

/** A phone or tablet: a finger, not a mouse and a keyboard. */
const TOUCH = "(pointer: coarse)";

/**
 * The shadcn dialog, minus focusing the first field on a touch screen.
 *
 * Radix moves focus into the first field when a dialog opens. With a keyboard
 * that saves a click; on a phone, focusing a field *opens* it — the keyboard
 * slides up over the form before it has been read, and a date field opens
 * its picker outright, so "Catat Panen" greeted you with a calendar to pick
 * from. On a touch screen focus goes to the dialog itself instead: screen
 * readers still land inside it, Escape still closes it, and nothing opens
 * until it is tapped.
 *
 * Here rather than in ui/dialog.tsx, which is regenerated by shadcn. Import
 * dialogs from this file.
 */
export function DialogContent({
  onOpenAutoFocus,
  ...props
}: React.ComponentProps<typeof BaseDialogContent>) {
  return (
    <BaseDialogContent
      {...props}
      onOpenAutoFocus={(event) => {
        onOpenAutoFocus?.(event);
        if (event.defaultPrevented || !window.matchMedia(TOUCH).matches) return;

        event.preventDefault();
        (event.currentTarget as HTMLElement | null)?.focus();
      }}
    />
  );
}
